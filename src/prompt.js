export const USER_PROMPT =
  "이 사진(들)에서 영양성분표를 읽어 스키마에 맞춰 추출하세요. 확신이 없는 값은 null로 두고 unreadable_fields에 기록하세요.";

/**
 * 1차 시도가 실패했을 때 쓰는 재시도 프롬프트.
 * 실패한 필드를 명시적으로 지목하면 모델이 그 영역을 다시 훑는다.
 */
export function buildRetryPrompt(previous) {
  const missing = [
    ...(previous?.unreadable_fields ?? []),
    ...Object.entries(previous?.nutrients ?? {})
      .filter(([, v]) => v === null)
      .map(([k]) => k),
  ];
  const uniq = [...new Set(missing)];

  return [
    "이 사진은 방금 한 번 판독을 시도했지만 일부 항목을 읽지 못했습니다.",
    uniq.length
      ? `특히 다음 항목을 표에서 다시 찾아보세요: ${uniq
          .map((k) => NUTRIENT_LABELS_KO[k] ?? k)
          .join(", ")}`
      : "전체 표를 다시 한 번 천천히 판독하세요.",
    "이번에는 더 높은 해상도의 이미지를 제공합니다. 표의 각 행을 위에서 아래로 한 줄씩 따라가며 읽으세요.",
    "그래도 확신이 안 서면 억지로 채우지 말고 null을 유지하세요.",
  ].join("\n");
}
